export function legacyItemName(name) {
    if(Object.hasOwn(names,name)) return names[name];
    if(Object.hasOwn(standalone,name)) return standalone[name];
    if(name.startsWith("Training Apprentice ")) {
        const noun=slots[name.slice("Training Apprentice ".length)];
        if(typeof noun==="string") return "Учебные "+noun.toLowerCase()+" ученика";
    }
    for(const prefix of prefixes) if(name.startsWith(prefix+" ")) {
        const noun=slots[name.slice(prefix.length+1)];
        if(typeof noun==="string") return noun+" "+sets[prefix];
    }
    return name;
}
